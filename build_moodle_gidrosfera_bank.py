R=ET.Element('quiz')
def tag(parent,name,text=None,**attrs):
    a=ET.SubElement(parent,name,attrs)
    if text is not None:a.text=str(text)
    return a
def val(p,name,value):return tag(tag(p,name),'text',value)
def question(typ,name,txt,feedback=None):
    q=tag(R,'question',type=typ);val(q,'name',name);val(tag(q,'questiontext',format='html'),'text',f'<p>{txt}</p>')
    if typ!='description':tag(q,'defaultgrade','1.0000000');tag(q,'penalty','0.3333333');tag(q,'hidden','0')
    if feedback:val(tag(q,'generalfeedback',format='html'),'text',f'<p>{feedback}</p>')
    return q
def ans(q,score,response,feedback=''):
    a=tag(q,'answer',fraction=str(score),format='moodle_auto_format');tag(a,'text',response)
    val(tag(a,'feedback',format='html'),'text',f'<p>{feedback}</p>' if feedback else '')
    return a
def mc(name,prompt,opts,correct,feedback, multiple=False):
    q=question('multichoice',name,prompt,feedback);tag(q,'single','false' if multiple else 'true');tag(q,'shuffleanswers','true');tag(q,'answernumbering','abc')
    for i,(o,explain) in enumerate(opts):ans(q,(100/len(correct) if i in correct else -50 if multiple else 0),o,explain)
    return q
def tf(name,statement,truth,explanation):
    q=question('truefalse',name,statement,explanation)
    ans(q,100 if truth else 0,'true');ans(q,0 if truth else 100,'false')
def short(name,prompt,correct,feedback):
    q=question('shortanswer',name,prompt,feedback);tag(q,'usecase','0')
    for value in correct:ans(q,100,value)
    ans(q,0,'*','Вспомните основные термины по теме.')
def num(name,prompt,value,tol,feedback):
    q=question('numerical',name,prompt,feedback);a=ans(q,100,str(value));tag(a,'tolerance',str(tol))
def match(name,prompt,pairs,feedback):
    q=question('matching',name,prompt,feedback);tag(q,'shuffleanswers','true')
    for left,right in pairs:
        a=tag(q,'subquestion',format='html');val(a,'text',f'<p>{left}</p>');tag(tag(a,'answer'),'text',right)
def essay(name,prompt,feedback):
    q=question('essay',name,prompt,feedback);tag(q,'responseformat','editor');tag(q,'responserequired','1');tag(q,'responsefieldlines','15');tag(q,'attachments','0');tag(q,'graderinfo',format='html').append(tag(ET.Element('placeholder'),'unused')) if False else None
def cloze(name,prompt,feedback):
    question('cloze',name,prompt,feedback)
def dd(name,prompt,words,feedback):
    q=question('ddwtos',name,prompt,feedback);tag(q,'shuffleanswers','1')
    for w in words:
        a=tag(q,'dragbox');tag(a,'text',w);tag(a,'group','1')
def gap(name,prompt,words,feedback):
    q=question('gapselect',name,prompt,feedback);tag(q,'shuffleanswers','1')
    for w in words:
        a=tag(q,'selectoption');tag(a,'text',w);tag(a,'group','1')
